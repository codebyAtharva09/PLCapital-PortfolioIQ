"""Generate docs/DATA_FINDINGS.md from the supplied data.

Run:  python -m portfolioiq.data_report

Every number is recomputed from the data on each run. The manual review notes at
the end record judgements no query can make, such as a sector label that differs
from common industry classification.
"""

from __future__ import annotations

import sqlite3

from portfolioiq.config import PROJECT_ROOT, load_settings
from portfolioiq.db import create_reference_db, row_counts

OUTPUT_PATH = PROJECT_ROOT / "docs" / "DATA_FINDINGS.md"

MANUAL_NOTES = [
    "**Home Depot (HD) is classified as Consumer Staples** in the supplied data, while common "
    "industry classification places it in Consumer Discretionary. The supplied assignment is "
    "preserved and flagged as a source-data classification anomaly wherever HD affects an answer "
    "(all of International Equity Fund's Consumer Staples exposure is HD).",
    "**`status` holds `Active` / `Passive`**, which reads as management style rather than "
    "lifecycle status. \"Active portfolios\" is taken literally as `status = 'Active'`.",
    "**`market_cap` units are not documented.** Values are consistent with USD millions "
    "(AAPL = 2,800,000), but answers do not assume a unit.",
    "**Two bonds mature after the data's as-of date but before today** (UST-2Y on 2024-01-15, "
    "UST-5Y on 2025-03-01). Answers are framed at the data's as-of date, not the current date.",
]


def build_report(conn: sqlite3.Connection) -> str:
    sections = [
        "# Data findings\n\n"
        "Generated by `python -m portfolioiq.data_report` from the supplied files, which are "
        "kept byte-identical to the originals (see `data/SHA256SUMS`). Rerun the script rather "
        "than editing this file.",
        _row_counts(conn),
        _portfolio_weights(conn),
        _weight_basis(conn),
        _reconciliation(conn),
        _coverage(conn),
        _reference_values(conn),
        "## 7. Manual review notes\n\n" + "\n".join(f"- {note}" for note in MANUAL_NOTES),
    ]
    return "\n\n".join(sections) + "\n"


def _row_counts(conn: sqlite3.Connection) -> str:
    rows = [[f"`{table}`", n] for table, n in row_counts(conn).items()]
    return "## 1. Row counts\n\n" + _table(["Table", "Rows"], rows)


def _portfolio_weights(conn: sqlite3.Connection) -> str:
    data = conn.execute(
        """
        SELECT p.portfolio_id, p.portfolio_name, COUNT(h.holding_id),
               COALESCE(SUM(h.current_weight), 0),
               COALESCE(SUM(CASE WHEN s.asset_type = 'Stock' THEN h.current_weight END), 0),
               COALESCE(SUM(CASE WHEN s.asset_type = 'Bond' THEN h.current_weight END), 0)
        FROM portfolios p
        LEFT JOIN holdings h ON h.portfolio_id = p.portfolio_id
        LEFT JOIN securities s ON s.security_id = h.security_id
        GROUP BY p.portfolio_id
        ORDER BY p.portfolio_id
        """
    ).fetchall()
    rows = []
    for pid, name, count, total, stocks, bonds in data:
        notes = []
        if abs(total - 1) > 1e-6:
            notes.append(f"holdings total {_pct(total)}; {_pct(1 - total)} unattributed")
        if stocks == 0:
            notes.append("no stocks: sector exposure not applicable")
        elif bonds > 0:
            notes.append("mixed: Methods A and B differ")
        rows.append([pid, name, count, _pct(total), _pct(stocks), _pct(bonds), "; ".join(notes)])
    intro = (
        "Sector exposure is calculated from `current_weight`. Method A keeps the whole portfolio "
        "as the denominator; Method B divides by the stock weight only. The two differ whenever "
        "a portfolio holds bonds or its weights do not total 100%."
    )
    headers = ["ID", "Portfolio", "Holdings", "Weight total", "Stocks", "Bonds", "Note"]
    return "## 2. Portfolio weights (`current_weight`)\n\n" + intro + "\n\n" + _table(headers, rows)


def _weight_basis(conn: sqlite3.Connection) -> str:
    data = conn.execute(
        """
        WITH v AS (
            SELECT h.portfolio_id, s.symbol, sec.sector_name, h.current_weight AS stated,
                   h.quantity * s.current_price
                     / SUM(h.quantity * s.current_price) OVER (PARTITION BY h.portfolio_id)
                     AS by_value
            FROM holdings h
            JOIN securities s ON s.security_id = h.security_id
            LEFT JOIN sectors sec ON sec.sector_id = s.sector_id
        )
        SELECT p.portfolio_name, v.symbol, v.sector_name, v.stated, v.by_value
        FROM v JOIN portfolios p ON p.portfolio_id = v.portfolio_id
        ORDER BY p.portfolio_id
        """
    ).fetchall()
    holdings_by_portfolio: dict[str, list[tuple]] = {}
    for name, symbol, sector, stated, by_value in data:
        holdings_by_portfolio.setdefault(name, []).append((symbol, sector, stated, by_value))
    rows = []
    for name, holdings in holdings_by_portfolio.items():
        tech_stated = sum(h[2] for h in holdings if h[1] == "Technology")
        tech_value = sum(h[3] for h in holdings if h[1] == "Technology")
        symbol, _, stated, by_value = max(holdings, key=lambda h: abs(h[2] - h[3]))
        gap = f"{symbol}: {_pct(stated)} stated vs {_pct(by_value)} by value"
        rows.append([name, _pct(tech_stated), _pct(tech_value), gap])
    intro = (
        "`current_weight` does not match each holding's share of market value "
        "(`quantity * current_price`, bonds included, as in Q7's reference SQL). The README "
        "specifies the exposure calculator on weights, while Q7's reference SQL uses market "
        "value, so the two can disagree for the same portfolio. Which basis exposure answers "
        "use is rule B1 in `docs/BUSINESS_RULES.md`."
    )
    headers = [
        "Portfolio",
        "Technology by `current_weight`",
        "Technology by market value",
        "Largest single-holding gap",
    ]
    return "## 3. Stated weights vs market value\n\n" + intro + "\n\n" + _table(headers, rows)


def _reconciliation(conn: sqlite3.Connection) -> str:
    data = conn.execute(
        """
        WITH tx AS (
            SELECT portfolio_id, security_id, COUNT(*) AS n,
                   SUM(CASE WHEN transaction_type = 'BUY' THEN quantity ELSE -quantity END) AS net
            FROM transactions
            GROUP BY portfolio_id, security_id
        )
        SELECT p.portfolio_name, s.symbol, h.quantity, tx.net, tx.n
        FROM tx
        JOIN portfolios p ON p.portfolio_id = tx.portfolio_id
        JOIN securities s ON s.security_id = tx.security_id
        LEFT JOIN holdings h
               ON h.portfolio_id = tx.portfolio_id AND h.security_id = tx.security_id
        ORDER BY tx.portfolio_id, s.symbol
        """
    ).fetchall()
    rows = [
        [name, symbol, _qty(held), _qty(net), n, _qty((held or 0) - net)]
        for name, symbol, held, net, n in data
    ]
    reconciled = sum(1 for r in data if r[2] is not None and abs(r[2] - r[3]) < 1e-9)
    distinct_dates, first_date = conn.execute(
        "SELECT COUNT(DISTINCT purchase_date), MIN(purchase_date) FROM holdings"
    ).fetchone()
    verb = "reconciles" if reconciled == 1 else "reconcile"
    intro = (
        f"{len(data)} positions have recorded transactions, and {reconciled} of them {verb} "
        "to the holdings quantity. The others are reconciliation gaps, not proven data errors: "
        "the transaction history may be incomplete."
    )
    if distinct_dates == 1:
        intro += f" Every holding carries the same `purchase_date` ({first_date})."
    headers = ["Portfolio", "Security", "Holdings qty", "Net transactions qty", "Transactions", "Gap"]
    return "## 4. Holdings vs transactions\n\n" + intro + "\n\n" + _table(headers, rows)


def _coverage(conn: sqlite3.Connection) -> str:
    rows = []
    for table, date_col in (
        ("portfolio_performance", "performance_date"),
        ("risk_metrics", "calculation_date"),
    ):
        ids = [str(r[0]) for r in conn.execute(f"SELECT DISTINCT portfolio_id FROM {table} ORDER BY 1")]
        first, last, days = conn.execute(
            f"SELECT MIN({date_col}), MAX({date_col}), COUNT(DISTINCT {date_col}) FROM {table}"
        ).fetchone()
        rows.append([f"`{table}`", "portfolios " + ", ".join(ids), f"{first} to {last}", days])
    securities, first, last, days = conn.execute(
        "SELECT COUNT(DISTINCT security_id), MIN(price_date), MAX(price_date), "
        "COUNT(DISTINCT price_date) FROM historical_prices"
    ).fetchone()
    rows.append(["`historical_prices`", f"{securities} securities", f"{first} to {last}", days])
    portfolios, first, last, days = conn.execute(
        "SELECT COUNT(DISTINCT portfolio_id), MIN(transaction_date), MAX(transaction_date), "
        "COUNT(DISTINCT transaction_date) FROM transactions"
    ).fetchone()
    rows.append(["`transactions`", f"{portfolios} portfolios", f"{first} to {last}", days])

    missing = [
        r[0]
        for r in conn.execute(
            """
            SELECT portfolio_name FROM portfolios
            WHERE portfolio_id NOT IN (SELECT portfolio_id FROM portfolio_performance)
              AND portfolio_id NOT IN (SELECT portfolio_id FROM risk_metrics)
            ORDER BY portfolio_id
            """
        )
    ]
    as_of = conn.execute(
        """
        SELECT MAX(d) FROM (
            SELECT MAX(price_date) AS d FROM historical_prices
            UNION ALL SELECT MAX(performance_date) FROM portfolio_performance
            UNION ALL SELECT MAX(calculation_date) FROM risk_metrics
        )
        """
    ).fetchone()[0]
    text = _table(["Table", "Covers", "Dates", "Distinct dates"], rows)
    text += (
        f"\n\nNo performance or risk data exists for: {', '.join(missing)}. Questions about these "
        "portfolios must say the data is unavailable rather than estimate it."
        f"\n\nLatest market-data date (the data's as-of date): **{as_of}**."
    )
    return "## 5. Coverage\n\n" + text


def _reference_values(conn: sqlite3.Connection) -> str:
    def counts(column: str, table: str) -> str:
        sql = f"SELECT {column}, COUNT(*) FROM {table} GROUP BY {column} ORDER BY {column}"
        return ", ".join(f"`{value}` ({n})" for value, n in conn.execute(sql))

    bonds_without_sector = conn.execute(
        "SELECT COUNT(*) FROM securities "
        "WHERE asset_type = 'Bond' AND sector_id IS NULL AND market_cap IS NULL"
    ).fetchone()[0]
    empty_sectors = [
        r[0]
        for r in conn.execute(
            "SELECT sector_name FROM sectors "
            "WHERE sector_id NOT IN (SELECT sector_id FROM securities WHERE sector_id IS NOT NULL) "
            "ORDER BY sector_name"
        )
    ]
    lines = [
        f"- `portfolios.status`: {counts('status', 'portfolios')}",
        f"- `portfolios.target_risk_level`: {counts('target_risk_level', 'portfolios')}",
        f"- `securities.asset_type`: {counts('asset_type', 'securities')}; "
        f"{bonds_without_sector} bonds have no sector and no market cap",
        f"- `securities.country`: {counts('country', 'securities')}. Every security is marked US, "
        "so answers make no geographic-diversification claims, including for the International "
        "and Emerging Markets funds.",
        f"- Sectors with no securities: {', '.join(empty_sectors)}. This is why Q6's reference "
        "result has 7 rows, not 10.",
    ]
    return "## 6. Reference values\n\n" + "\n".join(lines)


def _table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def _pct(fraction: float) -> str:
    return f"{fraction * 100:.2f}%"


def _qty(quantity: float | None) -> str:
    return "none" if quantity is None else f"{quantity:,.0f}"


def main() -> None:
    settings = load_settings()
    conn = create_reference_db(settings.data_dir, settings.schema_path)
    try:
        report = build_report(conn)
    finally:
        conn.close()
    OUTPUT_PATH.write_text(report, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT_PATH.relative_to(PROJECT_ROOT)} ({len(report.splitlines())} lines)")


if __name__ == "__main__":
    main()
